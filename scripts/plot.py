#!/usr/bin/env python3
"""
plot.py — Visualize FFT Spectrum Analyzer results.

Reads CSV files generated by spectrum_analyzer and plots:
  1. Time-domain signal (first 100ms)
  2. Frequency-domain magnitude spectrum (one-sided, 0 to Fs/2 Hz)

Requirements: Python 3.7+, matplotlib, numpy

Installation:
    pip install matplotlib numpy

Usage (from project root):
    python scripts/plot.py

    # Or specify custom CSV paths:
    python scripts/plot.py results/signal.csv results/spectrum.csv
"""

import sys
import os
import csv

# ── Try importing dependencies ────────────────────────────────
try:
    import matplotlib.pyplot as plt
    import matplotlib.gridspec as gridspec
    import numpy as np
except ImportError:
    print("Error: matplotlib and numpy are required.")
    print("Install with: pip install matplotlib numpy")
    sys.exit(1)


def read_csv(filepath: str) -> tuple[list, list]:
    """Read a two-column CSV file and return (col1_values, col2_values)."""
    col1, col2 = [], []
    if not os.path.exists(filepath):
        print(f"Error: File not found: {filepath}")
        sys.exit(1)
    with open(filepath, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            values = list(row.values())
            col1.append(float(values[0]))
            col2.append(float(values[1]))
    return col1, col2


def main():
    # ── File paths ───────────────────────────────────────────
    signal_file   = sys.argv[1] if len(sys.argv) > 1 else "results/signal.csv"
    spectrum_file = sys.argv[2] if len(sys.argv) > 2 else "results/spectrum.csv"

    print(f"Reading signal from   : {signal_file}")
    print(f"Reading spectrum from : {spectrum_file}")

    # ── Load data ────────────────────────────────────────────
    time_s, amplitude = read_csv(signal_file)
    freq_hz, magnitude = read_csv(spectrum_file)

    time_s    = np.array(time_s)
    amplitude = np.array(amplitude)
    freq_hz   = np.array(freq_hz)
    magnitude = np.array(magnitude)

    # ── Find peaks for annotation ────────────────────────────
    # Simple peak finding: top 2 bins by magnitude (excluding DC)
    peaks_idx = np.argsort(magnitude[1:])[::-1][:2] + 1  # skip DC (k=0)
    peak_freqs = freq_hz[peaks_idx]
    peak_mags  = magnitude[peaks_idx]

    # ── Plot setup ───────────────────────────────────────────
    plt.style.use('dark_background')
    fig = plt.figure(figsize=(14, 8), facecolor='#0d1117')
    fig.suptitle(
        'FFT-Based Digital Signal Spectrum Analyzer',
        fontsize=16, fontweight='bold', color='white', y=0.98
    )

    gs = gridspec.GridSpec(2, 1, figure=fig, hspace=0.45)

    # ── Plot 1: Time-domain signal ───────────────────────────
    ax1 = fig.add_subplot(gs[0])

    # Show first 100ms only (to see waveform clearly)
    show_duration_s = 0.1
    mask = time_s <= show_duration_s
    ax1.plot(
        time_s[mask] * 1000,  # Convert to milliseconds
        amplitude[mask],
        color='#58a6ff', linewidth=0.9, label='x(t) = sin(2π·50·t) + 0.5·sin(2π·120·t)'
    )
    ax1.set_xlabel('Time (ms)', color='#8b949e', fontsize=11)
    ax1.set_ylabel('Amplitude', color='#8b949e', fontsize=11)
    ax1.set_title('Time-Domain Signal (first 100 ms)', color='#e6edf3', fontsize=12)
    ax1.set_facecolor('#161b22')
    ax1.tick_params(colors='#8b949e')
    ax1.spines['bottom'].set_color('#30363d')
    ax1.spines['top'].set_color('#30363d')
    ax1.spines['left'].set_color('#30363d')
    ax1.spines['right'].set_color('#30363d')
    ax1.legend(loc='upper right', fontsize=9, labelcolor='#8b949e',
               facecolor='#0d1117', edgecolor='#30363d')
    ax1.grid(True, linestyle='--', alpha=0.3, color='#30363d')

    # ── Plot 2: Frequency-domain spectrum ────────────────────
    ax2 = fig.add_subplot(gs[1])

    ax2.fill_between(freq_hz, magnitude, alpha=0.3, color='#7ee787')
    ax2.plot(freq_hz, magnitude, color='#7ee787', linewidth=1.2)

    # Annotate detected peaks
    for i, (pf, pm) in enumerate(zip(peak_freqs, peak_mags)):
        ax2.annotate(
            f'{pf:.0f} Hz',
            xy=(pf, pm),
            xytext=(pf + 10, pm * 0.85),
            fontsize=10, color='#ffa657', fontweight='bold',
            arrowprops=dict(arrowstyle='->', color='#ffa657', lw=1.2),
        )
        ax2.axvline(x=pf, color='#ffa657', linestyle='--', alpha=0.5, linewidth=0.8)

    ax2.set_xlabel('Frequency (Hz)', color='#8b949e', fontsize=11)
    ax2.set_ylabel('Normalized Amplitude', color='#8b949e', fontsize=11)
    ax2.set_title('One-Sided FFT Magnitude Spectrum', color='#e6edf3', fontsize=12)
    ax2.set_facecolor('#161b22')
    ax2.tick_params(colors='#8b949e')
    ax2.spines['bottom'].set_color('#30363d')
    ax2.spines['top'].set_color('#30363d')
    ax2.spines['left'].set_color('#30363d')
    ax2.spines['right'].set_color('#30363d')
    ax2.set_xlim(0, max(freq_hz))
    ax2.grid(True, linestyle='--', alpha=0.3, color='#30363d')

    # ── Info box ─────────────────────────────────────────────
    info_text = (
        f"Fs = {freq_hz[-1]*2:.0f} Hz  |  "
        f"N = {len(time_s)}  |  "
        f"Resolution = {freq_hz[1]-freq_hz[0]:.2f} Hz/bin"
    )
    fig.text(0.5, 0.01, info_text, ha='center', fontsize=9, color='#8b949e')

    # ── Save and show ────────────────────────────────────────
    output_path = "results/spectrum_plot.png"
    plt.savefig(output_path, dpi=150, bbox_inches='tight', facecolor='#0d1117')
    print(f"Plot saved to: {output_path}")
    plt.show()


if __name__ == "__main__":
    main()
